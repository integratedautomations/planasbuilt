// Regenerates the built-in device icon library from a folder of SVGs.
//
//   node web/scripts/gen-pab-icons.mjs <icon-folder> [--check]
//
// <icon-folder> holds one sub-folder per category (access, automation, camera, fire, ...) of files named
// <category>-<device>-a.svg / -b.svg (option A and B), plus keywords.json mapping each file name to search keywords.
// Every SVG is validated (web/src/catalog/icons/pabValidate.ts): shapes only, no text / script / href / transform, and
// a note for anything drawn outside the [3, 21] safe area. Invalid files are NOT silently dropped: the script prints
// them and exits 1 without writing. Safe-area overruns are reported (and kept).
//
// Writes (UTF-8, LF):
//   web/src/catalog/icons/pabIcons.ts        artwork + keywords, used by the icon picker and .btx auto-icons
//   server/src/standardLibraryData.ts        names, mounts, prefixes, matchers + option A and B, used by the library installer
// Names, mounts, prefixes and matchers come from web/src/catalog/icons/pabSpec.ts.
// With --check nothing is written: the script only validates and compares against the committed files.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { validateSvg } from '../src/catalog/icons/pabValidate.ts'
import { DEVICES, PAB_CATEGORIES, deviceName } from '../src/catalog/icons/pabSpec.ts'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..', '..')
const args = process.argv.slice(2)
const check = args.includes('--check')
const dir = args.find(a => !a.startsWith('--'))
if (!dir || !existsSync(dir)) { console.error('usage: node web/scripts/gen-pab-icons.mjs <icon-folder> [--check]'); process.exit(2) }

const keywords = JSON.parse(readFileSync(join(dir, 'keywords.json'), 'utf8'))
const failures = [], outside = [], problems = []
const icons = [] // {slug, folder, keywords, a, b}

const specSlugs = new Set(DEVICES.map(x => x.slug))
const found = new Set()
for (const cat of PAB_CATEGORIES) {
  const folder = join(dir, cat.folder)
  if (!existsSync(folder)) { problems.push(`missing folder ${cat.folder}`); continue }
  const slugs = [...new Set(readdirSync(folder).filter(f => /-[ab]\.svg$/.test(f)).map(f => f.replace(/-[ab]\.svg$/, '')))].sort()
  for (const slug of slugs) {
    if (!slug.startsWith(cat.folder + '-')) problems.push(`${slug}: not prefixed with its folder name ${cat.folder}`)
    if (!specSlugs.has(slug)) problems.push(`${slug}: no entry in pabSpec.ts DEVICES (add a name, mount, prefix and matcher)`)
    found.add(slug)
    const bodies = {}
    for (const opt of ['a', 'b']) {
      const file = `${slug}-${opt}.svg`
      const path = join(folder, file)
      if (!existsSync(path)) { problems.push(`${file}: missing option ${opt.toUpperCase()}`); continue }
      const r = validateSvg(readFileSync(path, 'utf8'))
      if (!r.ok) { failures.push({ file, errors: r.errors }); continue }
      if (r.outsideSafeArea) outside.push({ file, bounds: r.bounds })
      bodies[opt] = r.body
    }
    const kw = keywords[`${slug}-a.svg`] ?? keywords[`${slug}-b.svg`]
    if (!kw) problems.push(`${slug}: no keywords in keywords.json`)
    if (bodies.a && bodies.b) icons.push({ slug, folder: cat.folder, keywords: kw ?? [], a: bodies.a, b: bodies.b })
  }
}
for (const s of specSlugs) if (!found.has(s)) problems.push(`${s}: in pabSpec.ts but no SVG in the folder`)

const f2 = n => (Math.round(n * 100) / 100)
console.log(`${icons.length} devices valid (${icons.length * 2} files).`)
if (outside.length) {
  console.log(`\n${outside.length} file(s) draw outside the [3, 21] safe area (kept):`)
  for (const o of outside) console.log(`  ${o.file}  x ${f2(o.bounds.x0)}..${f2(o.bounds.x1)}  y ${f2(o.bounds.y0)}..${f2(o.bounds.y1)}`)
}
if (failures.length) {
  console.log(`\n${failures.length} file(s) FAILED validation:`)
  for (const f of failures) console.log(`  ${f.file}: ${f.errors.join('; ')}`)
}
if (problems.length) {
  console.log(`\n${problems.length} problem(s):`)
  for (const p of problems) console.log(`  ${p}`)
}
if (failures.length || problems.length) { console.error('\nNothing written.'); process.exit(1) }

// ---- Output
const order = new Map(PAB_CATEGORIES.map((c, i) => [c.folder, i]))
icons.sort((x, y) => order.get(x.folder) - order.get(y.folder) || x.slug.localeCompare(y.slug))
const q = JSON.stringify

const web = `// GENERATED by web/scripts/gen-pab-icons.mjs from the icon set folders. Do not edit by hand; edit pabSpec.ts for names,
// mounts, prefixes and matchers, and re-run the script to change the artwork.
// Inner SVG markup (24x24, stroke 1.8, round caps, currentColor, no container) for option A and B of each device.

export interface PabIcon {
  /** File name without the -a / -b suffix, e.g. "fire-smoke". */
  slug: string
  /** Folder / category key, e.g. "fire". */
  folder: string
  keywords: string[]
  a: string
  b: string
}

export const PAB_ICONS: PabIcon[] = [
${icons.map(i => `  { slug: ${q(i.slug)}, folder: ${q(i.folder)}, keywords: ${q(i.keywords)}, a: ${q(i.a)}, b: ${q(i.b)} },`).join('\n')}
]
`

const bySlug = new Map(icons.map(i => [i.slug, i]))
const catOf = new Map(PAB_CATEGORIES.map(c => [c.folder, c]))
const server = `// GENERATED by web/scripts/gen-pab-icons.mjs (names, mounts, prefixes and matchers from web/src/catalog/icons/pabSpec.ts,
// artwork from the icon set). Do not edit by hand. Used by the "Standard device library" installer (standardLibrary.ts).

export interface StdSet { folder: string; name: string; color: string; tagPrefix: string; hasFov: boolean; iconSlug: string }
export interface StdDevice {
  slug: string
  folder: string
  name: string
  mount: 'ceiling' | 'wall' | 'square'
  tagPrefix: string
  coverage: { on: boolean; angle: number; range_ft: number } | null
  /** Regexp source matching a lower-cased device name; earlier devices win. */
  match: string
  /** Inner SVG markup of option A and B. */
  icon: string
  iconB: string
}

export const STD_SETS: StdSet[] = [
${PAB_CATEGORIES.map(c => `  { folder: ${q(c.folder)}, name: ${q(c.label)}, color: ${q(c.color)}, tagPrefix: ${q(c.prefix)}, hasFov: ${c.hasFov}, iconSlug: ${q(c.setIcon)} },`).join('\n')}
]

export const STD_DEVICES: StdDevice[] = [
${DEVICES.map(s => {
  const i = bySlug.get(s.slug)
  const folder = s.slug.split('-')[0]
  if (!catOf.has(folder)) throw new Error(`no category for ${s.slug}`)
  return `  { slug: ${q(s.slug)}, folder: ${q(folder)}, name: ${q(deviceName(s.slug))}, mount: ${q(s.mount)}, tagPrefix: ${q(s.prefix)}, coverage: ${s.coverage ? q(s.coverage) : 'null'}, match: ${q(s.match.source)}, icon: ${q(i.a)}, iconB: ${q(i.b)} },`
}).join('\n')}
]
`

const outs = [
  [join(root, 'web/src/catalog/icons/pabIcons.ts'), web],
  [join(root, 'server/src/standardLibraryData.ts'), server],
]
if (check) {
  let stale = false
  for (const [p, text] of outs) if (!existsSync(p) || readFileSync(p, 'utf8') !== text) { console.log(`out of date: ${p}`); stale = true }
  if (stale) process.exit(1)
  console.log('Generated files are up to date.')
} else {
  for (const [p, text] of outs) { writeFileSync(p, text, 'utf8'); console.log(`wrote ${p}`) }
}
